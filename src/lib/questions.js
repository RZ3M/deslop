// A post is hidden when any enabled category reaches its threshold.
// ai_generated is a Score (0 = clearly human … 3 = unmistakably AI) mapped to
// 0..1, so 0.67 means "Likely AI-generated" on average.
export const THRESHOLDS = {
  relaxed: { default: 0.9, ai_generated: 0.8, custom: 0.85 },
  balanced: { default: 0.8, ai_generated: 0.67, custom: 0.75 },
  strict: { default: 0.65, ai_generated: 0.55, custom: 0.6 },
};

// Choosing which blocked country a free-text location (e.g. a LinkedIn
// "San Francisco Bay Area") belongs to, when code-based matching fails.
export const NO_COUNTRY = 'none_of_these';
export const COUNTRY_CHOICE_MIN = 0.6;

export function locationQuestion(countryNames) {
  const criteria = {};
  for (const name of countryNames) criteria[name] = null;
  criteria[NO_COUNTRY] = 'The place is in a country not listed, or the country cannot be determined';
  return {
    type: 'choice',
    instructions: 'Which country is the place named in `location` in?',
    criteria,
  };
}

function noul(answer) {
  return answer && answer.type === 'noul' ? answer.noul : 0;
}

function scoreFraction(answer) {
  if (!answer || answer.type !== 'score') return 0;
  const levels = Object.keys(answer.legend || {}).length || 4;
  return answer.score / (levels - 1);
}
